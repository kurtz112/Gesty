-- Caratterizzazione del controllo delle ore settimanali di stage (specifica GESTY-TIR-003, Mantis #344).
-- Riparte dalla madre (ricrea CARATT_ESITI). Lo script va eseguito DOPO "GESTY-344-ore-settimanali-stage.sql" del
-- rilascio Ticket_Gesty/344 - QUESTIONI DA RISOLVERE/001 (procedura STUDENTI_TIROCINI_ORE_OLTRE_TETTO).
-- Dati di prova: un tirocinio con almeno tre settimane di durata e uno studente senza altre presenze nelle due
-- settimane usate, presi con SELECT FIRST 1, cosi' la prova gira su ogni copia che li ha (provata su CAPAC). Le
-- presenze di prova portano MATERIA = 'CARATT-344' e a fine prova si cancellano.
-- Non provati qui: l'avviso a fine "Genera Presenze" e l'elenco "Settimane Oltre Il Tetto" (interfaccia), da collaudare
-- con zapp sul banco; la somma su piu' tirocini dello stesso allievo (richiede un secondo tirocinio compatibile): la
-- procedura raggruppa per STUDENTI_TIROCINI.ID_STUDENTE e non per tirocinio.
SET TERM ^ ;

CREATE TABLE CARATT_ESITI (
    ID        INTEGER GENERATED BY DEFAULT AS IDENTITY,
    REQUISITO VARCHAR(20) NOT NULL,
    CASO      VARCHAR(200) NOT NULL,
    ATTESO    VARCHAR(10) NOT NULL,
    ESITO     VARCHAR(10),
    MESSAGGIO VARCHAR(1000)
)^

COMMIT^

CREATE PROCEDURE CARATT_REGISTRA (
    REQUISITO VARCHAR(20),
    CASO      VARCHAR(200),
    ATTESO    VARCHAR(10),
    MSG       VARCHAR(1000),
    ESITO     VARCHAR(10) = NULL)
AS
BEGIN
  -- transazione autonoma: i casi annotati prima di un eventuale fermo dello script non si perdono con il rollback
  IN AUTONOMOUS TRANSACTION DO
    INSERT INTO CARATT_ESITI (REQUISITO, CASO, ATTESO, ESITO, MESSAGGIO)
    VALUES (:REQUISITO, :CASO, :ATTESO, COALESCE(:ESITO, IIF(:MSG IS NULL, 'riuscito', 'errore')), :MSG);
END^

-- Registra un controllo sul dato: riuscito se la condizione e' vera
CREATE PROCEDURE CARATT_CONTROLLA (
    REQUISITO  VARCHAR(20),
    CASO       VARCHAR(200),
    CONDIZIONE BOOLEAN,
    DETTAGLIO  VARCHAR(500))
AS
BEGIN
  EXECUTE PROCEDURE CARATT_REGISTRA(:REQUISITO, :CASO, 'riuscito', :DETTAGLIO, TRIM(IIF(:CONDIZIONE, 'riuscito', 'errore')));
END^

COMMIT^

CREATE PROCEDURE CARATT_SCENARIO
AS
DECLARE VARIABLE TIROCINIO BIGINT;
DECLARE VARIABLE STUDENTE BIGINT;
DECLARE VARIABLE PRIMO_GIORNO DATE;
DECLARE VARIABLE LUNEDI_PROVA DATE;
DECLARE VARIABLE GIORNO INTEGER;
DECLARE VARIABLE RIGHE INTEGER;
DECLARE VARIABLE ORE NUMERIC(18,2);
DECLARE VARIABLE ECCESSO NUMERIC(18,2);
DECLARE VARIABLE LUNEDI_RESTITUITO DATE;
DECLARE VARIABLE DOMENICA_RESTITUITA DATE;
DECLARE VARIABLE TOTALE_PROCEDURA INTEGER;
DECLARE VARIABLE TOTALE_INDIPENDENTE INTEGER;
BEGIN
  -- primo tirocinio con almeno 21 giorni di durata, senza sospensioni o interruzioni, con studente libero nelle due settimane di prova
  TIROCINIO = (SELECT FIRST 1
                   STUDENTI_TIROCINI.ID_TIROCINIO
               FROM
                   STUDENTI_TIROCINI
               WHERE
                   STUDENTI_TIROCINI.DATA_FINE >= DATEADD(21 DAY TO STUDENTI_TIROCINI.DATA_INIZIO) AND
                   NOT EXISTS(SELECT 1 FROM STUDENTI_TIROCINI_PERIODI WHERE STUDENTI_TIROCINI_PERIODI.ID_TIROCINIO = STUDENTI_TIROCINI.ID_TIROCINIO AND STUDENTI_TIROCINI_PERIODI.TIPO_PERIODO IN ('S', 'I')) AND
                   NOT EXISTS(SELECT 1
                              FROM STUDENTI_PRESENZE_TIROCINIO
                                    INNER JOIN STUDENTI_TIROCINI ALTRO_TIROCINIO ON ALTRO_TIROCINIO.ID_TIROCINIO = STUDENTI_PRESENZE_TIROCINIO.ID_TIROCINIO
                              WHERE ALTRO_TIROCINIO.ID_STUDENTE = STUDENTI_TIROCINI.ID_STUDENTE AND
                                    STUDENTI_PRESENZE_TIROCINIO.DATA_LEZIONE BETWEEN DATEADD(7 DAY TO STUDENTI_TIROCINI.DATA_INIZIO) AND DATEADD(21 DAY TO STUDENTI_TIROCINI.DATA_INIZIO))
               ORDER BY
                   STUDENTI_TIROCINI.ID_TIROCINIO DESC);
  STUDENTE = (SELECT STUDENTI_TIROCINI.ID_STUDENTE FROM STUDENTI_TIROCINI WHERE STUDENTI_TIROCINI.ID_TIROCINIO = :TIROCINIO);
  PRIMO_GIORNO = (SELECT DATEADD(7 DAY TO STUDENTI_TIROCINI.DATA_INIZIO) FROM STUDENTI_TIROCINI WHERE STUDENTI_TIROCINI.ID_TIROCINIO = :TIROCINIO);
  -- lunedi della settimana che contiene PRIMO_GIORNO (EXTRACT(WEEKDAY): 0 domenica, 1 lunedi)
  LUNEDI_PROVA = DATEADD(DAY, -MOD(EXTRACT(WEEKDAY FROM :PRIMO_GIORNO) + 6, 7), :PRIMO_GIORNO);

  EXECUTE PROCEDURE CARATT_CONTROLLA('GESTY-TIR-003', 'dati di prova trovati (tirocinio e studente liberi)', :TIROCINIO IS NOT NULL AND :STUDENTE IS NOT NULL, 'tirocinio ' || COALESCE(:TIROCINIO, -1));

  -- Settimana da 40 ore esatte (lunedi-venerdi, 8 ore): non supera il tetto
  GIORNO = 0;
  WHILE (:GIORNO < 5) DO
  BEGIN
    INSERT INTO STUDENTI_PRESENZE_TIROCINIO (ID_TIROCINIO, DATA_LEZIONE, ORA_INIZIO, DURATA, MATERIA)
    VALUES (:TIROCINIO, DATEADD(:GIORNO DAY TO :LUNEDI_PROVA), '08:00', 480, 'CARATT-344');
    GIORNO = :GIORNO + 1;
  END
  RIGHE = (SELECT COUNT(*) FROM STUDENTI_TIROCINI_ORE_OLTRE_TETTO(NULL, NULL, :STUDENTE, NULL) WHERE STUDENTI_TIROCINI_ORE_OLTRE_TETTO.LUNEDI = :LUNEDI_PROVA);
  EXECUTE PROCEDURE CARATT_CONTROLLA('GESTY-TIR-003', '40 ore esatte in una settimana: nessuna segnalazione', :RIGHE = 0, 'righe: ' || :RIGHE);

  -- Un'ora il sabato: 41 ore, settimana segnalata con eccesso di 1 ora
  INSERT INTO STUDENTI_PRESENZE_TIROCINIO (ID_TIROCINIO, DATA_LEZIONE, ORA_INIZIO, DURATA, MATERIA)
  VALUES (:TIROCINIO, DATEADD(5 DAY TO :LUNEDI_PROVA), '08:00', 60, 'CARATT-344');
  SELECT STUDENTI_TIROCINI_ORE_OLTRE_TETTO.ORE_SETTIMANA, STUDENTI_TIROCINI_ORE_OLTRE_TETTO.ORE_IN_ECCESSO, STUDENTI_TIROCINI_ORE_OLTRE_TETTO.LUNEDI, STUDENTI_TIROCINI_ORE_OLTRE_TETTO.DOMENICA
  FROM STUDENTI_TIROCINI_ORE_OLTRE_TETTO(NULL, NULL, :STUDENTE, NULL)
  WHERE STUDENTI_TIROCINI_ORE_OLTRE_TETTO.LUNEDI = :LUNEDI_PROVA
  INTO :ORE, :ECCESSO, :LUNEDI_RESTITUITO, :DOMENICA_RESTITUITA;
  EXECUTE PROCEDURE CARATT_CONTROLLA('GESTY-TIR-003', '41 ore: settimana segnalata con 41 ore e 1 in eccesso', :ORE = 41 AND :ECCESSO = 1, 'ore ' || COALESCE(:ORE, -1) || ', eccesso ' || COALESCE(:ECCESSO, -1));
  EXECUTE PROCEDURE CARATT_CONTROLLA('GESTY-TIR-003', 'la settimana va dal lunedi alla domenica', :LUNEDI_RESTITUITO = :LUNEDI_PROVA AND :DOMENICA_RESTITUITA = DATEADD(6 DAY TO :LUNEDI_PROVA), 'dal ' || COALESCE(CAST(:LUNEDI_RESTITUITO AS VARCHAR(10)), 'nulla') || ' al ' || COALESCE(CAST(:DOMENICA_RESTITUITA AS VARCHAR(10)), 'nulla'));

  -- Il periodo chiesto si allarga alla settimana intera: chiedendo solo il sabato la somma resta di 41 ore
  ORE = NULL;
  SELECT STUDENTI_TIROCINI_ORE_OLTRE_TETTO.ORE_SETTIMANA
  FROM STUDENTI_TIROCINI_ORE_OLTRE_TETTO(DATEADD(5 DAY TO :LUNEDI_PROVA), DATEADD(5 DAY TO :LUNEDI_PROVA), :STUDENTE, NULL)
  INTO :ORE;
  EXECUTE PROCEDURE CARATT_CONTROLLA('GESTY-TIR-003', 'periodo di un solo giorno: somma della settimana intera', :ORE = 41, 'ore ' || COALESCE(:ORE, -1));

  -- Otto ore la domenica (ancora la stessa settimana) e otto ore il lunedi successivo (settimana nuova, non segnalata)
  INSERT INTO STUDENTI_PRESENZE_TIROCINIO (ID_TIROCINIO, DATA_LEZIONE, ORA_INIZIO, DURATA, MATERIA)
  VALUES (:TIROCINIO, DATEADD(6 DAY TO :LUNEDI_PROVA), '08:00', 480, 'CARATT-344');
  INSERT INTO STUDENTI_PRESENZE_TIROCINIO (ID_TIROCINIO, DATA_LEZIONE, ORA_INIZIO, DURATA, MATERIA)
  VALUES (:TIROCINIO, DATEADD(7 DAY TO :LUNEDI_PROVA), '08:00', 480, 'CARATT-344');
  ORE = (SELECT STUDENTI_TIROCINI_ORE_OLTRE_TETTO.ORE_SETTIMANA FROM STUDENTI_TIROCINI_ORE_OLTRE_TETTO(NULL, NULL, :STUDENTE, NULL) WHERE STUDENTI_TIROCINI_ORE_OLTRE_TETTO.LUNEDI = :LUNEDI_PROVA);
  RIGHE = (SELECT COUNT(*) FROM STUDENTI_TIROCINI_ORE_OLTRE_TETTO(NULL, NULL, :STUDENTE, NULL) WHERE STUDENTI_TIROCINI_ORE_OLTRE_TETTO.LUNEDI = DATEADD(7 DAY TO :LUNEDI_PROVA));
  EXECUTE PROCEDURE CARATT_CONTROLLA('GESTY-TIR-003', 'domenica nella stessa settimana: 49 ore', :ORE = 49, 'ore ' || COALESCE(:ORE, -1));
  EXECUTE PROCEDURE CARATT_CONTROLLA('GESTY-TIR-003', 'lunedi successivo: settimana nuova da 8 ore, non segnalata', :RIGHE = 0, 'righe: ' || :RIGHE);

  -- Le ore da non calcolare non contano
  UPDATE STUDENTI_PRESENZE_TIROCINIO SET STUDENTI_PRESENZE_TIROCINIO.CALCOLARE = FALSE
  WHERE STUDENTI_PRESENZE_TIROCINIO.ID_TIROCINIO = :TIROCINIO AND STUDENTI_PRESENZE_TIROCINIO.MATERIA = 'CARATT-344' AND STUDENTI_PRESENZE_TIROCINIO.DATA_LEZIONE IN (DATEADD(5 DAY TO :LUNEDI_PROVA), DATEADD(6 DAY TO :LUNEDI_PROVA));
  RIGHE = (SELECT COUNT(*) FROM STUDENTI_TIROCINI_ORE_OLTRE_TETTO(NULL, NULL, :STUDENTE, NULL) WHERE STUDENTI_TIROCINI_ORE_OLTRE_TETTO.LUNEDI = :LUNEDI_PROVA);
  EXECUTE PROCEDURE CARATT_CONTROLLA('GESTY-TIR-003', 'righe con CALCOLARE = FALSE non contano', :RIGHE = 0, 'righe: ' || :RIGHE);

  -- Le assenze (giustificate o no) non contano: contano solo le presenze
  UPDATE STUDENTI_PRESENZE_TIROCINIO SET STUDENTI_PRESENZE_TIROCINIO.CALCOLARE = TRUE, STUDENTI_PRESENZE_TIROCINIO.STATO_PRESENZA = 'A'
  WHERE STUDENTI_PRESENZE_TIROCINIO.ID_TIROCINIO = :TIROCINIO AND STUDENTI_PRESENZE_TIROCINIO.MATERIA = 'CARATT-344' AND STUDENTI_PRESENZE_TIROCINIO.DATA_LEZIONE IN (DATEADD(5 DAY TO :LUNEDI_PROVA), DATEADD(6 DAY TO :LUNEDI_PROVA));
  RIGHE = (SELECT COUNT(*) FROM STUDENTI_TIROCINI_ORE_OLTRE_TETTO(NULL, NULL, :STUDENTE, NULL) WHERE STUDENTI_TIROCINI_ORE_OLTRE_TETTO.LUNEDI = :LUNEDI_PROVA);
  EXECUTE PROCEDURE CARATT_CONTROLLA('GESTY-TIR-003', 'le assenze non contano', :RIGHE = 0, 'righe: ' || :RIGHE);

  -- Il tetto si puo' passare: con 35 ore le 40 della settimana regolare superano di 5
  ECCESSO = NULL;
  SELECT STUDENTI_TIROCINI_ORE_OLTRE_TETTO.ORE_IN_ECCESSO
  FROM STUDENTI_TIROCINI_ORE_OLTRE_TETTO(NULL, NULL, :STUDENTE, 35)
  WHERE STUDENTI_TIROCINI_ORE_OLTRE_TETTO.LUNEDI = :LUNEDI_PROVA
  INTO :ECCESSO;
  EXECUTE PROCEDURE CARATT_CONTROLLA('GESTY-TIR-003', 'tetto passato come parametro (35)', :ECCESSO = 5, 'eccesso ' || COALESCE(:ECCESSO, -1));

  -- Controllo incrociato su tutti i dati: stessa risposta di una somma scritta a parte
  TOTALE_PROCEDURA = (SELECT COUNT(*) FROM STUDENTI_TIROCINI_ORE_OLTRE_TETTO(NULL, NULL, NULL, NULL));
  TOTALE_INDIPENDENTE = (SELECT COUNT(*)
                         FROM (SELECT
                                   STUDENTI_TIROCINI.ID_STUDENTE,
                                   CAST(STUDENTI_PRESENZE_TIROCINIO.DATA_LEZIONE - MOD(EXTRACT(WEEKDAY FROM STUDENTI_PRESENZE_TIROCINIO.DATA_LEZIONE) + 6, 7) AS DATE) INIZIO_SETTIMANA
                               FROM
                                   STUDENTI_PRESENZE_TIROCINIO
                                         INNER JOIN STUDENTI_TIROCINI ON STUDENTI_TIROCINI.ID_TIROCINIO = STUDENTI_PRESENZE_TIROCINIO.ID_TIROCINIO
                               WHERE
                                   STUDENTI_PRESENZE_TIROCINIO.PRESENTE = TRUE AND
                                   STUDENTI_PRESENZE_TIROCINIO.CALCOLARE = TRUE
                               GROUP BY
                                   1, 2
                               HAVING
                                   SUM(ORE_100_FROM_MINUTI(STUDENTI_PRESENZE_TIROCINIO.DURATA)) > 40) SETTIMANE_OLTRE_TETTO);
  EXECUTE PROCEDURE CARATT_CONTROLLA('GESTY-TIR-003', 'numero di settimane oltre il tetto uguale a una somma indipendente', :TOTALE_PROCEDURA = :TOTALE_INDIPENDENTE, 'procedura ' || :TOTALE_PROCEDURA || ', somma indipendente ' || :TOTALE_INDIPENDENTE);

  -- pulizia: presenze di prova cancellate
  DELETE FROM STUDENTI_PRESENZE_TIROCINIO WHERE STUDENTI_PRESENZE_TIROCINIO.ID_TIROCINIO = :TIROCINIO AND STUDENTI_PRESENZE_TIROCINIO.MATERIA = 'CARATT-344';
END^

COMMIT^

EXECUTE PROCEDURE CARATT_SCENARIO^

SET TERM ; ^

COMMIT;
