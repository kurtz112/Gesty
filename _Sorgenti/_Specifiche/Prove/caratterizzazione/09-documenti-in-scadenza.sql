-- Caratterizzazione della data di fine validita' dei documenti allegati (specifica GESTY-STA-021).
-- Riparte dalla madre (ricrea CARATT_ESITI). Lo script va eseguito DOPO "GESTY-341-documenti-scadenza.sql" del
-- rilascio Ticket_Gesty/341 - QUESTIONI DA RISOLVERE/003.
-- Dati di prova: risorsa persona con un incarico in corso o futuro e richiesta di attivazione presi dal database con
-- SELECT FIRST 1, cosi' la prova gira su ogni copia che li ha (provata su CAPAC). I documenti di prova si creano con
-- OBJ_FILES_ADD e a fine prova si eliminano (ELIMINATO = TRUE); l'utente che sottoscrive l'avviso e' il primo utente.
-- Contesto utente simulato con RDB$SET_CONTEXT, come in Aule e prenotazioni: prova le regole di trigger e procedure,
-- non il modo in cui l'applicazione costruisce il contesto.
-- Non provati qui: la scheda allegati e la guida di attivazione (interfaccia), da collaudare con zapp sul banco; le
-- procedure RICHIESTE_ATTIV_COPIA_FILE e RICHIESTA_ATTIV_GENERA_RISORSA (copia della data), che richiedono una richiesta
-- completa.
SET TERM ^ ;

CREATE TABLE CARATT_ESITI (
    ID        INTEGER GENERATED BY DEFAULT AS IDENTITY,
    REQUISITO VARCHAR(20) NOT NULL,
    CASO      VARCHAR(200) NOT NULL,
    ATTESO    VARCHAR(10) NOT NULL,
    ESITO     VARCHAR(10),
    MESSAGGIO VARCHAR(1000)
)^

COMMIT^

CREATE PROCEDURE CARATT_REGISTRA (
    REQUISITO VARCHAR(20),
    CASO      VARCHAR(200),
    ATTESO    VARCHAR(10),
    MSG       VARCHAR(1000),
    ESITO     VARCHAR(10) = NULL)
AS
BEGIN
  -- transazione autonoma: i casi annotati prima di un eventuale fermo dello script non si perdono con il rollback
  IN AUTONOMOUS TRANSACTION DO
    INSERT INTO CARATT_ESITI (REQUISITO, CASO, ATTESO, ESITO, MESSAGGIO)
    VALUES (:REQUISITO, :CASO, :ATTESO, COALESCE(:ESITO, IIF(:MSG IS NULL, 'riuscito', 'errore')), :MSG);
END^

-- Esegue un comando e registra l'esito; TESTO (facoltativo) e' un pezzo del messaggio atteso per un errore
CREATE PROCEDURE CARATT_ESEGUI (
    REQUISITO VARCHAR(20),
    CASO      VARCHAR(200),
    ATTESO    VARCHAR(10),
    TESTO     VARCHAR(200),
    COMANDO   VARCHAR(2000))
AS
DECLARE VARIABLE MSG   VARCHAR(1000);
DECLARE VARIABLE ESITO VARCHAR(10);
BEGIN
  MSG = NULL;
  BEGIN
    EXECUTE STATEMENT :COMANDO;
  WHEN ANY DO
    MSG = SUBSTRING(RDB$ERROR(MESSAGE) FROM 1 FOR 1000);
  END
  ESITO = TRIM(IIF(:MSG IS NULL, 'riuscito', IIF(:TESTO IS NOT NULL AND :MSG NOT CONTAINING :TESTO, 'diverso', 'errore')));
  EXECUTE PROCEDURE CARATT_REGISTRA(:REQUISITO, :CASO, :ATTESO, :MSG, :ESITO);
END^

-- Registra un controllo sul dato: riuscito se la condizione e' vera
CREATE PROCEDURE CARATT_CONTROLLA (
    REQUISITO  VARCHAR(20),
    CASO       VARCHAR(200),
    CONDIZIONE BOOLEAN,
    DETTAGLIO  VARCHAR(500))
AS
BEGIN
  EXECUTE PROCEDURE CARATT_REGISTRA(:REQUISITO, :CASO, 'riuscito', :DETTAGLIO, TRIM(IIF(:CONDIZIONE, 'riuscito', 'errore')));
END^

COMMIT^

CREATE PROCEDURE CARATT_SCENARIO
AS
DECLARE VARIABLE UTENTE BIGINT;
DECLARE VARIABLE RISORSA BIGINT;
DECLARE VARIABLE NOMINATIVO VARCHAR(100);
DECLARE VARIABLE RICHIESTA BIGINT;
DECLARE VARIABLE FILE_NUOVO BIGINT;
DECLARE VARIABLE FILE_ALTRO BIGINT;
DECLARE VARIABLE FILE_COPIA BIGINT;
DECLARE VARIABLE FILE_RICHIESTA BIGINT;
DECLARE VARIABLE DUMMY_NOME VARCHAR(255);
DECLARE VARIABLE DUMMY_COMPLETO VARCHAR(255);
DECLARE VARIABLE DATA_COPIA DATE;
DECLARE VARIABLE QUANTI INTEGER;
DECLARE VARIABLE MANCANTI VARCHAR(2000);
DECLARE VARIABLE TESTO VARCHAR(8000);
DECLARE VARIABLE DUMMY VARCHAR(255);
BEGIN
  RISORSA = (SELECT FIRST 1
                 RISORSE_ELENCO.ID_RISORSA
             FROM
                 RISORSE_ELENCO
             WHERE
                 RISORSE_ELENCO.TIPO_RISORSA = 'P' AND
                 EXISTS(SELECT 1 FROM INCARICHI WHERE INCARICHI.ID_RISORSA = RISORSE_ELENCO.ID_RISORSA AND INCARICHI.DATA_RESPINGIMENTO IS NULL AND INCARICHI.DATA_FINE_INCARICO >= CURRENT_DATE) AND
                 NOT EXISTS(SELECT 1 FROM OBJ_FILES WHERE OBJ_FILES.OID = RISORSE_ELENCO.ID_RISORSA AND OBJ_FILES.TIPO_ALLEGATO = 'CARTA D''IDENTITA')
             ORDER BY
                 RISORSE_ELENCO.ID_RISORSA DESC);
  NOMINATIVO = (SELECT RISORSE_ELENCO.NOMINATIVO_O_RAGIONE_SOCIALE FROM RISORSE_ELENCO WHERE RISORSE_ELENCO.ID_RISORSA = :RISORSA);
  RICHIESTA = (SELECT FIRST 1 RICHIESTE_ATTIVAZIONE.ID_RICHIESTA_ATTIVAZIONE FROM RICHIESTE_ATTIVAZIONE WHERE NOT EXISTS(SELECT 1 FROM OBJ_FILES WHERE OBJ_FILES.OID = RICHIESTE_ATTIVAZIONE.ID_RICHIESTA_ATTIVAZIONE AND OBJ_FILES.TIPO_ALLEGATO = 'CARTA D''IDENTITA' AND OBJ_FILES.ANNULLATO = FALSE AND OBJ_FILES.ELIMINATO = FALSE) ORDER BY RICHIESTE_ATTIVAZIONE.ID_RICHIESTA_ATTIVAZIONE DESC);
  UTENTE = (SELECT FIRST 1 USR_UTENTI.USER_ID FROM USR_UTENTI ORDER BY USR_UTENTI.USER_ID);

  DUMMY = RDB$SET_CONTEXT('USER_SESSION', 'CURRENT_USER_ID', :UTENTE);

  EXECUTE PROCEDURE CARATT_CONTROLLA('GESTY-STA-021', 'dati di prova trovati (risorsa con incarico e senza carta, richiesta, utente)', :RISORSA IS NOT NULL AND :RICHIESTA IS NOT NULL AND :UTENTE IS NOT NULL, 'risorsa ' || COALESCE(:RISORSA, -1));

  -- GESTY-STA-021 Configurazione: la carta d'identita' richiede la data, gli altri tipi no
  QUANTI = (SELECT COUNT(*) FROM ZZ_TIPO_ALLEGATI WHERE ZZ_TIPO_ALLEGATI.DATA_SCADENZA_OBBLIGATORIA = TRUE AND ZZ_TIPO_ALLEGATI.TIPO_ALLEGATO <> 'CARTA D''IDENTITA');
  EXECUTE PROCEDURE CARATT_CONTROLLA('GESTY-STA-021', 'solo la carta d''identita'' richiede la data', :QUANTI = 0 AND (SELECT ZZ_TIPO_ALLEGATI.DATA_SCADENZA_OBBLIGATORIA FROM ZZ_TIPO_ALLEGATI WHERE ZZ_TIPO_ALLEGATI.TIPO_ALLEGATO = 'CARTA D''IDENTITA') = TRUE, 'altri tipi: ' || :QUANTI);

  -- GESTY-STA-021 Ingresso automatico: OBJ_FILES_ADD con tipo e senza data non e' bloccato
  EXECUTE PROCEDURE OBJ_FILES_ADD(:RISORSA, 'CARTA D''IDENTITA', 'P', 'carta-prova-automatica.pdf', NULL, 0, NULL, '?')
      RETURNING_VALUES :FILE_ALTRO, :DUMMY_NOME, :DUMMY_COMPLETO;
  EXECUTE PROCEDURE CARATT_CONTROLLA('GESTY-STA-021', 'ingresso automatico con tipo e senza data non bloccato', :FILE_ALTRO IS NOT NULL, 'allegato ' || COALESCE(:FILE_ALTRO, -1));

  -- GESTY-STA-021 Allegato preesistente senza data: si puo' modificare altro senza essere costretti a inserirla
  EXECUTE PROCEDURE CARATT_ESEGUI('GESTY-STA-021', 'allegato preesistente senza data, modifica della descrizione', 'riuscito', NULL, 'UPDATE OBJ_FILES_ELENCO SET DESC_FILE = ''descrizione prova'' WHERE ID_OBJECT_FILE = ' || :FILE_ALTRO);

  -- GESTY-STA-021 Importazione manuale: il file entra senza tipo, il tipo si assegna dopo
  EXECUTE PROCEDURE OBJ_FILES_ADD(:RISORSA, NULL, 'P', 'carta-prova-manuale.pdf', NULL, 0, NULL, '?')
      RETURNING_VALUES :FILE_NUOVO, :DUMMY_NOME, :DUMMY_COMPLETO;
  EXECUTE PROCEDURE CARATT_ESEGUI('GESTY-STA-021', 'tipo carta d''identita'' assegnato senza data', 'errore', 'data di scadenza', 'UPDATE OBJ_FILES_ELENCO SET TIPO_ALLEGATO = ''CARTA D''''IDENTITA'' WHERE ID_OBJECT_FILE = ' || :FILE_NUOVO);
  EXECUTE PROCEDURE CARATT_ESEGUI('GESTY-STA-021', 'tipo diverso assegnato senza data', 'riuscito', NULL, 'UPDATE OBJ_FILES_ELENCO SET TIPO_ALLEGATO = ''ALTRO'' WHERE ID_OBJECT_FILE = ' || :FILE_NUOVO);
  EXECUTE PROCEDURE CARATT_ESEGUI('GESTY-STA-021', 'tipo carta d''identita'' assegnato con la data', 'riuscito', NULL, 'UPDATE OBJ_FILES_ELENCO SET TIPO_ALLEGATO = ''CARTA D''''IDENTITA'', DATA_SCADENZA_DOCUMENTO = DATEADD(2 YEAR TO CURRENT_DATE) WHERE ID_OBJECT_FILE = ' || :FILE_NUOVO);
  EXECUTE PROCEDURE CARATT_ESEGUI('GESTY-STA-021', 'cancellazione della data di una carta', 'errore', 'data di scadenza', 'UPDATE OBJ_FILES_ELENCO SET DATA_SCADENZA_DOCUMENTO = NULL WHERE ID_OBJECT_FILE = ' || :FILE_NUOVO);
  EXECUTE PROCEDURE CARATT_ESEGUI('GESTY-STA-021', 'annullo di un allegato senza data', 'riuscito', NULL, 'UPDATE OBJ_FILES_ELENCO SET ANNULLATO = TRUE, DATA_SCADENZA_DOCUMENTO = NULL WHERE ID_OBJECT_FILE = ' || :FILE_ALTRO);
  EXECUTE PROCEDURE CARATT_CONTROLLA('GESTY-STA-021', 'la vista espone la data e il campo SCADUTO', (SELECT OBJ_FILES_ELENCO.DATA_SCADENZA_DOCUMENTO IS NOT NULL AND OBJ_FILES_ELENCO.SCADUTO = FALSE FROM OBJ_FILES_ELENCO WHERE OBJ_FILES_ELENCO.ID_OBJECT_FILE = :FILE_NUOVO), 'allegato ' || :FILE_NUOVO);

  -- GESTY-STA-022 La copia dell'allegato porta la data
  EXECUTE PROCEDURE OBJ_FILES_COPY(:FILE_NUOVO, :RICHIESTA)
      RETURNING_VALUES :FILE_COPIA, :DUMMY_NOME, :DUMMY_COMPLETO;
  DATA_COPIA = (SELECT OBJ_FILES.DATA_SCADENZA_DOCUMENTO FROM OBJ_FILES WHERE OBJ_FILES.ID_OBJECT_FILE = :FILE_COPIA);
  EXECUTE PROCEDURE CARATT_CONTROLLA('GESTY-STA-022', 'OBJ_FILES_COPY copia la data di fine validita''', :DATA_COPIA = DATEADD(2 YEAR TO CURRENT_DATE), 'data copiata: ' || COALESCE(CAST(:DATA_COPIA AS VARCHAR(10)), 'nulla'));

  -- GESTY-STA-023 Guida di attivazione: un allegato con tipo che richiede la data e senza data blocca la richiesta
  EXECUTE PROCEDURE OBJ_FILES_ADD(:RICHIESTA, 'CARTA D''IDENTITA', 'P', 'carta-richiesta-prova.pdf', NULL, 0, NULL, '?')
      RETURNING_VALUES :FILE_RICHIESTA, :DUMMY_NOME, :DUMMY_COMPLETO;
  EXECUTE PROCEDURE RICHIESTE_ATTIV_VERIFICA_ALLEG(:RICHIESTA, FALSE) RETURNING_VALUES :MANCANTI;
  EXECUTE PROCEDURE CARATT_CONTROLLA('GESTY-STA-023', 'richiesta con carta senza data: allegato segnalato', COALESCE(:MANCANTI, '') CONTAINING 'indicare la data di scadenza', 'mancanti: ' || COALESCE(:MANCANTI, 'nessuno'));
  UPDATE OBJ_FILES SET OBJ_FILES.DATA_SCADENZA_DOCUMENTO = DATEADD(1 YEAR TO CURRENT_DATE) WHERE OBJ_FILES.ID_OBJECT_FILE = :FILE_RICHIESTA;
  MANCANTI = NULL;
  EXECUTE PROCEDURE RICHIESTE_ATTIV_VERIFICA_ALLEG(:RICHIESTA, FALSE) RETURNING_VALUES :MANCANTI;
  EXECUTE PROCEDURE CARATT_CONTROLLA('GESTY-STA-023', 'richiesta con carta con data: nessuna segnalazione sulla data', COALESCE(:MANCANTI, '') NOT CONTAINING 'indicare la data di scadenza', 'mancanti: ' || COALESCE(:MANCANTI, 'nessuno'));

  -- GESTY-STA-024 Avviso notturno
  DELETE FROM NOTIFICHE WHERE NOTIFICHE.NOTIFICA = 'DOCUMENTO_IN_SCADENZA';
  INSERT INTO USR_UTENTI_SOTTOSCRIZIONI_NOTIFICHE (USER_ID, NOTIFICA) VALUES (:UTENTE, 'DOCUMENTO_IN_SCADENZA');

  -- carta in scadenza entro la soglia (30 giorni di predefinito)
  UPDATE OBJ_FILES SET OBJ_FILES.DATA_SCADENZA_DOCUMENTO = DATEADD(10 DAY TO CURRENT_DATE) WHERE OBJ_FILES.ID_OBJECT_FILE = :FILE_NUOVO;
  EXECUTE PROCEDURE CRON_VERIFICA_DOCUMENTI_IN_SCADENZA;
  TESTO = (SELECT FIRST 1 NOTIFICHE.MESSAGGIO FROM NOTIFICHE WHERE NOTIFICHE.NOTIFICA = 'DOCUMENTO_IN_SCADENZA' AND NOTIFICHE.USER_ID_DESTINATARIO = :UTENTE ORDER BY NOTIFICHE.ID_NOTIFICA DESC);
  EXECUTE PROCEDURE CARATT_CONTROLLA('GESTY-STA-024', 'carta in scadenza fra 10 giorni: nell''elenco In scadenza', COALESCE(:TESTO, '') CONTAINING 'In scadenza entro' AND COALESCE(:TESTO, '') CONTAINING (:NOMINATIVO || ' - CARTA'), 'avviso: ' || COALESCE(LEFT(:TESTO, 150), 'nessuno'));

  -- lo stesso elenco non si ripete
  EXECUTE PROCEDURE CRON_VERIFICA_DOCUMENTI_IN_SCADENZA;
  QUANTI = (SELECT COUNT(*) FROM NOTIFICHE WHERE NOTIFICHE.NOTIFICA = 'DOCUMENTO_IN_SCADENZA' AND NOTIFICHE.USER_ID_DESTINATARIO = :UTENTE);
  EXECUTE PROCEDURE CARATT_CONTROLLA('GESTY-STA-024', 'stesso elenco: un solo avviso', :QUANTI = 1, 'avvisi: ' || :QUANTI);

  -- carta scaduta: l'elenco cambia, nuovo avviso con la risorsa fra gli scaduti
  UPDATE OBJ_FILES SET OBJ_FILES.DATA_SCADENZA_DOCUMENTO = DATEADD(-5 DAY TO CURRENT_DATE) WHERE OBJ_FILES.ID_OBJECT_FILE = :FILE_NUOVO;
  EXECUTE PROCEDURE CRON_VERIFICA_DOCUMENTI_IN_SCADENZA;
  TESTO = (SELECT FIRST 1 NOTIFICHE.MESSAGGIO FROM NOTIFICHE WHERE NOTIFICHE.NOTIFICA = 'DOCUMENTO_IN_SCADENZA' AND NOTIFICHE.USER_ID_DESTINATARIO = :UTENTE ORDER BY NOTIFICHE.ID_NOTIFICA DESC);
  QUANTI = (SELECT COUNT(*) FROM NOTIFICHE WHERE NOTIFICHE.NOTIFICA = 'DOCUMENTO_IN_SCADENZA' AND NOTIFICHE.USER_ID_DESTINATARIO = :UTENTE);
  EXECUTE PROCEDURE CARATT_CONTROLLA('GESTY-STA-024', 'carta scaduta: nuovo avviso con la risorsa fra gli scaduti', :QUANTI = 2 AND COALESCE(:TESTO, '') CONTAINING 'Scaduti (' AND COALESCE(:TESTO, '') CONTAINING (:NOMINATIVO || ' - CARTA'), 'avvisi: ' || :QUANTI);

  -- carta valida (oltre la soglia): la risorsa non compare piu' nelle liste scaduti e in scadenza
  UPDATE OBJ_FILES SET OBJ_FILES.DATA_SCADENZA_DOCUMENTO = DATEADD(400 DAY TO CURRENT_DATE) WHERE OBJ_FILES.ID_OBJECT_FILE = :FILE_NUOVO;
  EXECUTE PROCEDURE CRON_VERIFICA_DOCUMENTI_IN_SCADENZA;
  TESTO = (SELECT FIRST 1 NOTIFICHE.MESSAGGIO FROM NOTIFICHE WHERE NOTIFICHE.NOTIFICA = 'DOCUMENTO_IN_SCADENZA' AND NOTIFICHE.USER_ID_DESTINATARIO = :UTENTE ORDER BY NOTIFICHE.ID_NOTIFICA DESC);
  EXECUTE PROCEDURE CARATT_CONTROLLA('GESTY-STA-024', 'carta valida: la risorsa non compare nell''avviso', COALESCE(:TESTO, '') NOT CONTAINING (:NOMINATIVO || ' - CARTA'), 'avviso: ' || COALESCE(LEFT(:TESTO, 150), 'nessuno'));

  -- pulizia: documenti di prova eliminati, avvisi e sottoscrizione tolti
  UPDATE OBJ_FILES SET OBJ_FILES.ELIMINATO = TRUE WHERE OBJ_FILES.ID_OBJECT_FILE IN (:FILE_NUOVO, :FILE_ALTRO, :FILE_COPIA, :FILE_RICHIESTA);
  DELETE FROM NOTIFICHE WHERE NOTIFICHE.NOTIFICA = 'DOCUMENTO_IN_SCADENZA';
  DELETE FROM USR_UTENTI_SOTTOSCRIZIONI_NOTIFICHE WHERE USR_UTENTI_SOTTOSCRIZIONI_NOTIFICHE.USER_ID = :UTENTE AND USR_UTENTI_SOTTOSCRIZIONI_NOTIFICHE.NOTIFICA = 'DOCUMENTO_IN_SCADENZA';
  DUMMY = RDB$SET_CONTEXT('USER_SESSION', 'CURRENT_USER_ID', NULL);
END^

COMMIT^

EXECUTE PROCEDURE CARATT_SCENARIO^

SET TERM ; ^

COMMIT;
