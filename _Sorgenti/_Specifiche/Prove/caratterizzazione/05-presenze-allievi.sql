-- Caratterizzazione di Presenze allievi e registro (specifica GESTY-PRE-*), prima puntata: presenze collettive.
-- Riparte dalla madre (ricrea CARATT_ESITI). Dati: progetto 470701, corso 473403, allievi 443455 (A, iscrizione 15439),
-- 473407 (B, iscrizione 15511) e 86440 (C, iscrizione 16329). Le lezioni di prova sono nuove: L1-L5 a gennaio 2027,
-- T1 e T2 il 6 e 7 luglio 2026 (dopo l'ultima lezione reale, 29 giugno 2026, e prima di oggi).
-- Atteso = cio' che dice la specifica; per le divergenze (DIV-PRE-*) atteso = il comportamento descritto nella divergenza.
-- Non provati qui: PRE-010 (sovrapposizione fra tipi di presenza), PRE-011 e PRE-013 (firma e sblocco: stanno nel programma),
-- PRE-017 (serve una trasmissione SIUF), DIV-PRE-3, 4, 7, 8, 9.
