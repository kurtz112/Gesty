-- Caratterizzazione di Progettazione bandi (specifica GESTY-BAN-*).
-- Riparte dalla madre (ricrea CARATT_ESITI). Lo script va eseguito DOPO "01 - Bandi struttura database.sql" del
-- rilascio OUT/20261107-modulo-progettazione-bandi-codebri/001.
-- Dati di prova: ente e bandi nuovi; settore con responsabile che ha un utente, progetto senza data di approvazione e
-- senza fonte presi dal database con SELECT FIRST 1, cosi' la prova gira su ogni copia che li ha (provata su CODEBRI).
-- Contesto utente simulato con RDB$SET_CONTEXT e USR_TMP_AUTHORIZATIONS (CARATT_UTENTE), come in Aule e prenotazioni:
-- prova le regole di trigger e procedure, non il modo in cui l'applicazione costruisce il contesto.
-- Non provati qui: GESTY-BAN-012 (interfaccia), da collaudare con zapp sul banco.
SET TERM ^ ;

CREATE TABLE CARATT_ESITI (
    ID        INTEGER GENERATED BY DEFAULT AS IDENTITY,
    REQUISITO VARCHAR(20) NOT NULL,
    CASO      VARCHAR(200) NOT NULL,
    ATTESO    VARCHAR(10) NOT NULL,
    ESITO     VARCHAR(10),
    MESSAGGIO VARCHAR(1000)
)^

COMMIT^

CREATE PROCEDURE CARATT_REGISTRA (
    REQUISITO VARCHAR(20),
    CASO      VARCHAR(200),
    ATTESO    VARCHAR(10),
    MSG       VARCHAR(1000),
    ESITO     VARCHAR(10) = NULL)
AS
BEGIN
  INSERT INTO CARATT_ESITI (REQUISITO, CASO, ATTESO, ESITO, MESSAGGIO)
  VALUES (:REQUISITO, :CASO, :ATTESO, COALESCE(:ESITO, IIF(:MSG IS NULL, 'riuscito', 'errore')), :MSG);
END^

-- Utente simulato: risorsa, utente e autorizzazioni (nomi separati da punto e virgola)
CREATE PROCEDURE CARATT_UTENTE (
    RIS      BIGINT,
    UTENTE   BIGINT,
    ELENCO   VARCHAR(500))
AS
DECLARE VARIABLE DUMMY VARCHAR(255);
DECLARE VARIABLE RESTO VARCHAR(500);
DECLARE VARIABLE VOCE  VARCHAR(100);
DECLARE VARIABLE POSIZIONE INTEGER;
BEGIN
  DELETE FROM USR_TMP_AUTHORIZATIONS;
  RESTO = COALESCE(:ELENCO, '');
  WHILE (:RESTO <> '') DO
  BEGIN
    POSIZIONE = POSITION(';' IN :RESTO);
    IF (:POSIZIONE = 0) THEN
    BEGIN
      VOCE = :RESTO;
      RESTO = '';
    END
    ELSE
    BEGIN
      VOCE = LEFT(:RESTO, :POSIZIONE - 1);
      RESTO = SUBSTRING(:RESTO FROM :POSIZIONE + 1);
    END
    INSERT INTO USR_TMP_AUTHORIZATIONS ("AUTHORIZATION") VALUES (:VOCE);
  END
  DUMMY = RDB$SET_CONTEXT('USER_SESSION', 'CURRENT_ID_RISORSA', :RIS);
  DUMMY = RDB$SET_CONTEXT('USER_SESSION', 'CURRENT_USER_ID', :UTENTE);
END^

-- Esegue un comando e registra l'esito; TESTO (facoltativo) e' un pezzo del messaggio atteso per un errore
CREATE PROCEDURE CARATT_ESEGUI (
    REQUISITO VARCHAR(20),
    CASO      VARCHAR(200),
    ATTESO    VARCHAR(10),
    TESTO     VARCHAR(200),
    COMANDO   VARCHAR(2000))
AS
DECLARE VARIABLE MSG   VARCHAR(1000);
DECLARE VARIABLE ESITO VARCHAR(10);
BEGIN
  MSG = NULL;
  BEGIN
    EXECUTE STATEMENT :COMANDO;
  WHEN ANY DO
    MSG = SUBSTRING(RDB$ERROR(MESSAGE) FROM 1 FOR 1000);
  END
  ESITO = TRIM(IIF(:MSG IS NULL, 'riuscito', IIF(:TESTO IS NOT NULL AND :MSG NOT CONTAINING :TESTO, 'diverso', 'errore')));
  EXECUTE PROCEDURE CARATT_REGISTRA(:REQUISITO, :CASO, :ATTESO, :MSG, :ESITO);
END^

-- Registra un controllo sul dato: riuscito se la condizione e' vera
CREATE PROCEDURE CARATT_CONTROLLA (
    REQUISITO  VARCHAR(20),
    CASO       VARCHAR(200),
    CONDIZIONE BOOLEAN,
    DETTAGLIO  VARCHAR(500))
AS
BEGIN
  EXECUTE PROCEDURE CARATT_REGISTRA(:REQUISITO, :CASO, 'riuscito', :DETTAGLIO, TRIM(IIF(:CONDIZIONE, 'riuscito', 'errore')));
END^

