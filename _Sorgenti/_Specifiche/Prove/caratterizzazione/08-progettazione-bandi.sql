CREATE PROCEDURE CARATT_SCENARIO
AS
DECLARE VARIABLE GESTIONE VARCHAR(500) = 'Bandi.Gestione';
DECLARE VARIABLE TUTTE VARCHAR(500) = 'Bandi.Gestione;Bandi.Parere.UfficioProgetti;Bandi.Parere.Settore;Bandi.Parere.Finanziario';
DECLARE VARIABLE ENTE BIGINT;
DECLARE VARIABLE BANDO BIGINT;
DECLARE VARIABLE SCARTATO BIGINT;
DECLARE VARIABLE DA_ELIMINARE BIGINT;
DECLARE VARIABLE CANDIDATURA BIGINT;
DECLARE VARIABLE SETTORE VARCHAR(5);
DECLARE VARIABLE RESPONSABILE BIGINT;
DECLARE VARIABLE UTENTE_RESPONSABILE BIGINT;
DECLARE VARIABLE UTENTE BIGINT;
DECLARE VARIABLE PROGETTO BIGINT;
DECLARE VARIABLE QUANTI INTEGER;
DECLARE VARIABLE DATA_APPROVAZIONE DATE;
DECLARE VARIABLE DUMMY VARCHAR(255);
BEGIN
  SELECT FIRST 1
      ZZ_SETTORI_AZIENDALI_RESPONSAB.CODICE_SETTORE_AZIENDALE,
      ZZ_SETTORI_AZIENDALI_RESPONSAB.ID_RESPONSABILE_SETTORE,
      USR_UTENTI.USER_ID
  FROM
      ZZ_SETTORI_AZIENDALI_RESPONSAB
            INNER JOIN USR_UTENTI ON USR_UTENTI.ID_ANAGRAFICA = ZZ_SETTORI_AZIENDALI_RESPONSAB.ID_RESPONSABILE_SETTORE
  WHERE
      ZZ_SETTORI_AZIENDALI_RESPONSAB.DATA_FINE_VALIDITA >= CURRENT_DATE
  INTO
      :SETTORE,
      :RESPONSABILE,
      :UTENTE_RESPONSABILE;

  UTENTE = (SELECT FIRST 1 USR_UTENTI.USER_ID FROM USR_UTENTI WHERE USR_UTENTI.USER_ID <> :UTENTE_RESPONSABILE ORDER BY USR_UTENTI.USER_ID);

  PROGETTO = (SELECT FIRST 1
                  PROGETTI.ID_PROGETTO
              FROM
                  PROGETTI
              WHERE
                  PROGETTI.DATA_APPROVAZIONE_BANDO IS NULL AND
                  PROGETTI.FONTE_FINANZIAMENTO IS NULL
              ORDER BY
                  PROGETTI.ID_PROGETTO DESC);

  -- GESTY-BAN-001 Autorizzazioni
  EXECUTE PROCEDURE CARATT_UTENTE(0, :UTENTE, '');
  EXECUTE PROCEDURE CARATT_ESEGUI('GESTY-BAN-001', 'ente finanziatore senza Bandi.Gestione', 'errore', 'Bandi.Gestione', 'INSERT INTO ENTI_FINANZIATORI (DESC_ENTE_FINANZIATORE) VALUES (''Ente senza permesso'')');

  EXECUTE PROCEDURE CARATT_UTENTE(0, :UTENTE, :GESTIONE);
  INSERT INTO ENTI_FINANZIATORI (DESC_ENTE_FINANZIATORE) VALUES ('Ente di prova') RETURNING ID_ENTE_FINANZIATORE INTO :ENTE;

  EXECUTE PROCEDURE CARATT_UTENTE(0, :UTENTE, '');
  EXECUTE PROCEDURE CARATT_ESEGUI('GESTY-BAN-001', 'bando senza Bandi.Gestione', 'errore', 'Bandi.Gestione', 'INSERT INTO BANDI (ID_ENTE_FINANZIATORE, DESC_BANDO) VALUES (' || :ENTE || ', ''Bando vietato'')');

  EXECUTE PROCEDURE CARATT_UTENTE(0, :UTENTE, :GESTIONE);

  -- GESTY-BAN-002 Dati del bando
  EXECUTE PROCEDURE CARATT_ESEGUI('GESTY-BAN-002', 'territorio comunale senza nome del comune', 'errore', 'territorio', 'INSERT INTO BANDI (ID_ENTE_FINANZIATORE, DESC_BANDO, TERRITORIO) VALUES (' || :ENTE || ', ''Bando comunale'', ''COM'')');
  EXECUTE PROCEDURE CARATT_ESEGUI('GESTY-BAN-002', 'data dei pareri dopo la scadenza del bando', 'errore', 'data ultima', 'INSERT INTO BANDI (ID_ENTE_FINANZIATORE, DESC_BANDO, DATA_SCADENZA, DATA_SCADENZA_PARERI) VALUES (' || :ENTE || ', ''Bando date'', DATE ''2030-01-10'', DATE ''2030-01-20'')');

  INSERT INTO BANDI (ID_ENTE_FINANZIATORE, DESC_BANDO, IMPORTO_MASSIMO_FINANZIAMENTO, CODICE_SETTORE_AZIENDALE, DATA_SCADENZA)
  VALUES (:ENTE, 'Bando di prova', 50000, :SETTORE, DATEADD(60 DAY TO CURRENT_DATE))
  RETURNING ID_BANDO INTO :BANDO;

  -- GESTY-BAN-003 Stato del bando
  EXECUTE PROCEDURE CARATT_CONTROLLA('GESTY-BAN-003', 'bando nuovo rilevato', BANDO_FASE(:BANDO) = 'RILEVATO', BANDO_FASE(:BANDO));

  -- GESTY-BAN-004 Ordine dei livelli
  EXECUTE PROCEDURE CARATT_UTENTE(0, :UTENTE, :TUTTE);
  EXECUTE PROCEDURE CARATT_ESEGUI('GESTY-BAN-004', 'parere di settore prima dell''Ufficio Progetti', 'errore', 'livelli precedenti', 'EXECUTE PROCEDURE BANDO_PARERE(' || :BANDO || ', ''SETTORE'', ''POS'', NULL)');

  -- GESTY-BAN-005 Chi esprime il parere
  EXECUTE PROCEDURE CARATT_UTENTE(0, :UTENTE, :GESTIONE);
  EXECUTE PROCEDURE CARATT_ESEGUI('GESTY-BAN-005', 'parere senza l''autorizzazione del livello', 'errore', 'abilitati', 'EXECUTE PROCEDURE BANDO_PARERE(' || :BANDO || ', ''UFFICIO_PROGETTI'', ''POS'', NULL)');

  -- GESTY-BAN-006 Parere contrario motivato
  EXECUTE PROCEDURE CARATT_UTENTE(0, :UTENTE, :TUTTE);
  EXECUTE PROCEDURE CARATT_ESEGUI('GESTY-BAN-006', 'parere contrario senza motivazione', 'errore', 'motivazione', 'EXECUTE PROCEDURE BANDO_PARERE(' || :BANDO || ', ''UFFICIO_PROGETTI'', ''NEG'', '' '')');

  -- GESTY-BAN-007 I pareri non si scrivono a mano
  EXECUTE PROCEDURE CARATT_ESEGUI('GESTY-BAN-007', 'parere inserito direttamente in tabella', 'errore', 'non si modificano', 'INSERT INTO BANDI_PARERI (ID_BANDO, LIVELLO_VALUTAZIONE, ESITO, USER_ID_PARERE) VALUES (' || :BANDO || ', ''UFFICIO_PROGETTI'', ''POS'', ' || :UTENTE || ')');

  -- GESTY-BAN-004 e 008: primo livello, poi i due in parallelo in ordine qualunque
  EXECUTE PROCEDURE CARATT_ESEGUI('GESTY-BAN-004', 'parere favorevole dell''Ufficio Progetti', 'riuscito', NULL, 'EXECUTE PROCEDURE BANDO_PARERE(' || :BANDO || ', ''UFFICIO_PROGETTI'', ''POS'', NULL)');
  EXECUTE PROCEDURE CARATT_CONTROLLA('GESTY-BAN-003', 'in valutazione dopo il primo parere', BANDO_FASE(:BANDO) = 'IN_VALUTAZIONE', BANDO_FASE(:BANDO));
  EXECUTE PROCEDURE CARATT_ESEGUI('GESTY-BAN-004', 'stesso parere due volte', 'errore', 'stato espresso', 'EXECUTE PROCEDURE BANDO_PARERE(' || :BANDO || ', ''UFFICIO_PROGETTI'', ''POS'', NULL)');

  QUANTI = (SELECT COUNT(*) FROM NOTIFICHE WHERE NOTIFICHE.NOTIFICA = 'BANDO_DA_VALUTARE' AND NOTIFICHE.TAG_ID = :BANDO AND NOTIFICHE.USER_ID_DESTINATARIO = :UTENTE_RESPONSABILE);
  EXECUTE PROCEDURE CARATT_CONTROLLA('GESTY-BAN-010', 'avviso al responsabile del settore quando tocca al suo livello', :QUANTI = 1, 'avvisi: ' || :QUANTI);

  EXECUTE PROCEDURE CARATT_ESEGUI('GESTY-BAN-008', 'parere finanziario prima di quello di settore', 'riuscito', NULL, 'EXECUTE PROCEDURE BANDO_PARERE(' || :BANDO || ', ''FINANZIARIO'', ''POS'', NULL)');
  EXECUTE PROCEDURE CARATT_CONTROLLA('GESTY-BAN-008', 'ancora in valutazione con un solo parere del gruppo', BANDO_FASE(:BANDO) = 'IN_VALUTAZIONE', BANDO_FASE(:BANDO));

  -- GESTY-BAN-009 candidatura solo su bando approvato
  EXECUTE PROCEDURE CARATT_UTENTE(0, :UTENTE, :GESTIONE);
  EXECUTE PROCEDURE CARATT_ESEGUI('GESTY-BAN-009', 'candidatura su un bando non approvato', 'errore', 'bando approvato', 'INSERT INTO BANDI_CANDIDATURE (ID_BANDO, TITOLO_PROGETTO) VALUES (' || :BANDO || ', ''Candidatura anticipata'')');

  -- GESTY-BAN-005 il responsabile del settore del bando si esprime senza autorizzazione
  EXECUTE PROCEDURE CARATT_UTENTE(:RESPONSABILE, :UTENTE_RESPONSABILE, '');
  EXECUTE PROCEDURE CARATT_ESEGUI('GESTY-BAN-005', 'responsabile del settore senza autorizzazione', 'riuscito', NULL, 'EXECUTE PROCEDURE BANDO_PARERE(' || :BANDO || ', ''SETTORE'', ''POS'', NULL)');
  EXECUTE PROCEDURE CARATT_CONTROLLA('GESTY-BAN-003', 'approvato con tutti i livelli attivi favorevoli', BANDO_FASE(:BANDO) = 'APPROVATO', BANDO_FASE(:BANDO));

  -- GESTY-BAN-009 Candidatura e sequenza
  EXECUTE PROCEDURE CARATT_UTENTE(0, :UTENTE, :GESTIONE);
  INSERT INTO BANDI_CANDIDATURE (ID_BANDO, TITOLO_PROGETTO, BUDGET_TOTALE, IMPORTO_FINANZIAMENTO, BUDGET_GESTITO_ENTE)
  VALUES (:BANDO, 'Candidatura di prova', 60000, 40000, 30000)
  RETURNING ID_CANDIDATURA INTO :CANDIDATURA;

  EXECUTE PROCEDURE CARATT_CONTROLLA('GESTY-BAN-009', 'cofinanziamento calcolato', (SELECT BANDI_CANDIDATURE.IMPORTO_COFINANZIAMENTO FROM BANDI_CANDIDATURE WHERE BANDI_CANDIDATURE.ID_CANDIDATURA = :CANDIDATURA) = 20000, NULL);
  EXECUTE PROCEDURE CARATT_ESEGUI('GESTY-BAN-009', 'finanziamento oltre il budget', 'errore', 'budget totale', 'UPDATE BANDI_CANDIDATURE SET BUDGET_TOTALE = 1000 WHERE ID_CANDIDATURA = ' || :CANDIDATURA);
  EXECUTE PROCEDURE CARATT_ESEGUI('GESTY-BAN-009', 'finanziamento oltre il massimo del bando', 'errore', 'importo massimo', 'UPDATE BANDI_CANDIDATURE SET BUDGET_TOTALE = 90000, IMPORTO_FINANZIAMENTO = 60000 WHERE ID_CANDIDATURA = ' || :CANDIDATURA);
  EXECUTE PROCEDURE CARATT_ESEGUI('GESTY-BAN-011', 'esito senza presentazione', 'errore', 'presentata', 'UPDATE BANDI_CANDIDATURE SET ESITO = ''APP'', DATA_ESITO = CURRENT_DATE WHERE ID_CANDIDATURA = ' || :CANDIDATURA);
  EXECUTE PROCEDURE CARATT_ESEGUI('GESTY-BAN-011', 'rinuncia senza motivo', 'errore', 'motivo', 'UPDATE BANDI_CANDIDATURE SET DATA_RINUNCIA = CURRENT_DATE WHERE ID_CANDIDATURA = ' || :CANDIDATURA);
  EXECUTE PROCEDURE CARATT_ESEGUI('GESTY-BAN-011', 'presentazione', 'riuscito', NULL, 'UPDATE BANDI_CANDIDATURE SET DATA_PRESENTAZIONE = CURRENT_DATE WHERE ID_CANDIDATURA = ' || :CANDIDATURA);
  EXECUTE PROCEDURE CARATT_ESEGUI('GESTY-BAN-011', 'esito negativo senza motivo', 'errore', 'mancata approvazione', 'UPDATE BANDI_CANDIDATURE SET ESITO = ''NAP'', DATA_ESITO = CURRENT_DATE WHERE ID_CANDIDATURA = ' || :CANDIDATURA);
  EXECUTE PROCEDURE CARATT_ESEGUI('GESTY-BAN-011', 'assegnazione senza approvazione', 'errore', 'approvata', 'UPDATE BANDI_CANDIDATURE SET DATA_ASSEGNAZIONE = CURRENT_DATE WHERE ID_CANDIDATURA = ' || :CANDIDATURA);
  EXECUTE PROCEDURE CARATT_ESEGUI('GESTY-BAN-011', 'esito positivo', 'riuscito', NULL, 'UPDATE BANDI_CANDIDATURE SET ESITO = ''APP'', DATA_ESITO = CURRENT_DATE WHERE ID_CANDIDATURA = ' || :CANDIDATURA);
  EXECUTE PROCEDURE CARATT_ESEGUI('GESTY-BAN-011', 'chiusura senza assegnazione', 'errore', 'assegnata', 'UPDATE BANDI_CANDIDATURE SET DATA_CHIUSURA = CURRENT_DATE WHERE ID_CANDIDATURA = ' || :CANDIDATURA);

  -- GESTY-BAN-013 Collegamento al progetto
  EXECUTE PROCEDURE CARATT_ESEGUI('GESTY-BAN-013', 'assegnazione e collegamento al progetto', 'riuscito', NULL, 'UPDATE BANDI_CANDIDATURE SET DATA_ASSEGNAZIONE = CURRENT_DATE, ID_PROGETTO = ' || :PROGETTO || ' WHERE ID_CANDIDATURA = ' || :CANDIDATURA);
  DATA_APPROVAZIONE = (SELECT PROGETTI.DATA_APPROVAZIONE_BANDO FROM PROGETTI WHERE PROGETTI.ID_PROGETTO = :PROGETTO);
  EXECUTE PROCEDURE CARATT_CONTROLLA('GESTY-BAN-013', 'il progetto riceve la data di approvazione', :DATA_APPROVAZIONE = CURRENT_DATE, NULL);

  -- GESTY-BAN-014 Confronto con il Budget
  EXECUTE PROCEDURE CARATT_CONTROLLA('GESTY-BAN-014', 'candidatura presente nell''andamento', EXISTS(SELECT 1 FROM BANDI_CANDIDATURE_ANDAMENTO WHERE BANDI_CANDIDATURE_ANDAMENTO.ID_CANDIDATURA = :CANDIDATURA AND BANDI_CANDIDATURE_ANDAMENTO.FASE = 'IN_ESECUZIONE'), NULL);
  EXECUTE PROCEDURE CARATT_CONTROLLA('GESTY-BAN-014', 'senza autorizzazione Budget il residuo resta nascosto', (SELECT BANDI_CANDIDATURE_ANDAMENTO.BUDGET_RESIDUO FROM BANDI_CANDIDATURE_ANDAMENTO WHERE BANDI_CANDIDATURE_ANDAMENTO.ID_CANDIDATURA = :CANDIDATURA) = 0, NULL);
  EXECUTE PROCEDURE CARATT_UTENTE(0, :UTENTE, 'Bandi.Gestione;Budget');
  EXECUTE PROCEDURE CARATT_CONTROLLA('GESTY-BAN-014', 'con autorizzazione Budget il residuo si vede', (SELECT BANDI_CANDIDATURE_ANDAMENTO.BUDGET_RESIDUO FROM BANDI_CANDIDATURE_ANDAMENTO WHERE BANDI_CANDIDATURE_ANDAMENTO.ID_CANDIDATURA = :CANDIDATURA) <> 0, NULL);

  -- GESTY-BAN-011 candidatura chiusa
  EXECUTE PROCEDURE CARATT_UTENTE(0, :UTENTE, :GESTIONE);
  EXECUTE PROCEDURE CARATT_ESEGUI('GESTY-BAN-011', 'chiusura', 'riuscito', NULL, 'UPDATE BANDI_CANDIDATURE SET DATA_CHIUSURA = CURRENT_DATE WHERE ID_CANDIDATURA = ' || :CANDIDATURA);
  EXECUTE PROCEDURE CARATT_ESEGUI('GESTY-BAN-011', 'modifica di una candidatura chiusa senza Bandi.Supervisore', 'errore', 'Bandi.Supervisore', 'UPDATE BANDI_CANDIDATURE SET NOTE = ''x'' WHERE ID_CANDIDATURA = ' || :CANDIDATURA);

  -- GESTY-BAN-015 Riapertura
  EXECUTE PROCEDURE CARATT_UTENTE(0, :UTENTE, 'Bandi.Gestione;Bandi.Supervisore;Bandi.Parere.UfficioProgetti');
  EXECUTE PROCEDURE CARATT_ESEGUI('GESTY-BAN-015', 'riapertura di un bando con candidature', 'errore', 'candidature', 'EXECUTE PROCEDURE BANDO_RIAPRI_VALUTAZIONE(' || :BANDO || ', ''motivo'')');

  INSERT INTO BANDI (ID_ENTE_FINANZIATORE, DESC_BANDO) VALUES (:ENTE, 'Bando da scartare') RETURNING ID_BANDO INTO :SCARTATO;
  EXECUTE PROCEDURE CARATT_ESEGUI('GESTY-BAN-006', 'parere contrario motivato', 'riuscito', NULL, 'EXECUTE PROCEDURE BANDO_PARERE(' || :SCARTATO || ', ''UFFICIO_PROGETTI'', ''NEG'', ''Fuori dalle linee dell ente'')');
  EXECUTE PROCEDURE CARATT_CONTROLLA('GESTY-BAN-003', 'scartato dopo un parere contrario', BANDO_FASE(:SCARTATO) = 'SCARTATO', BANDO_FASE(:SCARTATO));
  EXECUTE PROCEDURE CARATT_ESEGUI('GESTY-BAN-006', 'altro parere su un bando scartato', 'errore', 'scartato', 'EXECUTE PROCEDURE BANDO_PARERE(' || :SCARTATO || ', ''UFFICIO_PROGETTI'', ''POS'', NULL)');

  EXECUTE PROCEDURE CARATT_UTENTE(0, :UTENTE, :GESTIONE);
  EXECUTE PROCEDURE CARATT_ESEGUI('GESTY-BAN-015', 'riapertura senza Bandi.Supervisore', 'errore', 'Bandi.Supervisore', 'EXECUTE PROCEDURE BANDO_RIAPRI_VALUTAZIONE(' || :SCARTATO || ', ''motivo'')');

  EXECUTE PROCEDURE CARATT_UTENTE(0, :UTENTE, 'Bandi.Gestione;Bandi.Supervisore');
  EXECUTE PROCEDURE CARATT_ESEGUI('GESTY-BAN-015', 'riapertura senza motivo', 'errore', 'motivo', 'EXECUTE PROCEDURE BANDO_RIAPRI_VALUTAZIONE(' || :SCARTATO || ', '' '')');
  EXECUTE PROCEDURE CARATT_ESEGUI('GESTY-BAN-015', 'riapertura', 'riuscito', NULL, 'EXECUTE PROCEDURE BANDO_RIAPRI_VALUTAZIONE(' || :SCARTATO || ', ''Rivalutazione chiesta dalla direzione'')');
  EXECUTE PROCEDURE CARATT_CONTROLLA('GESTY-BAN-015', 'dopo la riapertura il bando riparte', BANDO_FASE(:SCARTATO) = 'RILEVATO', BANDO_FASE(:SCARTATO));
  EXECUTE PROCEDURE CARATT_CONTROLLA('GESTY-BAN-015', 'il parere annullato resta nello storico', EXISTS(SELECT 1 FROM BANDI_PARERI WHERE BANDI_PARERI.ID_BANDO = :SCARTATO AND BANDI_PARERI.DATA_ORA_ANNULLAMENTO IS NOT NULL), NULL);

  -- GESTY-BAN-016 Livelli configurabili: la direzione accesa diventa un livello in piu'
  EXECUTE PROCEDURE CARATT_UTENTE(0, :UTENTE, :GESTIONE);
  EXECUTE PROCEDURE CARATT_ESEGUI('GESTY-BAN-016', 'modifica dei livelli senza Bandi.Supervisore', 'errore', 'Bandi.Supervisore', 'UPDATE ZZ_BANDI_LIVELLI_VALUTAZIONE SET ATTIVO = TRUE WHERE LIVELLO_VALUTAZIONE = ''DIREZIONE''');
  EXECUTE PROCEDURE CARATT_UTENTE(0, :UTENTE, 'Bandi.Gestione;Bandi.Supervisore');
  UPDATE ZZ_BANDI_LIVELLI_VALUTAZIONE SET ZZ_BANDI_LIVELLI_VALUTAZIONE.ATTIVO = TRUE WHERE ZZ_BANDI_LIVELLI_VALUTAZIONE.LIVELLO_VALUTAZIONE = 'DIREZIONE';
  EXECUTE PROCEDURE CARATT_CONTROLLA('GESTY-BAN-016', 'con la direzione attiva il bando approvato torna in valutazione', BANDO_FASE(:BANDO) = 'IN_VALUTAZIONE', BANDO_FASE(:BANDO));
  UPDATE ZZ_BANDI_LIVELLI_VALUTAZIONE SET ZZ_BANDI_LIVELLI_VALUTAZIONE.ATTIVO = FALSE WHERE ZZ_BANDI_LIVELLI_VALUTAZIONE.LIVELLO_VALUTAZIONE = 'DIREZIONE';

  -- GESTY-BAN-010 Avviso di scadenza, una volta sola
  INSERT INTO USR_UTENTI_SOTTOSCRIZIONI_NOTIFICHE (USER_ID, NOTIFICA) VALUES (:UTENTE, 'BANDO_IN_SCADENZA');
  INSERT INTO BANDI (ID_ENTE_FINANZIATORE, DESC_BANDO, DATA_SCADENZA) VALUES (:ENTE, 'Bando in scadenza', DATEADD(3 DAY TO CURRENT_DATE)) RETURNING ID_BANDO INTO :DA_ELIMINARE;
  EXECUTE PROCEDURE CRON_VERIFICA_SCADENZA_BANDI;
  EXECUTE PROCEDURE CRON_VERIFICA_SCADENZA_BANDI;
  QUANTI = (SELECT COUNT(*) FROM NOTIFICHE WHERE NOTIFICHE.NOTIFICA = 'BANDO_IN_SCADENZA' AND NOTIFICHE.TAG_ID = :DA_ELIMINARE AND NOTIFICHE.USER_ID_DESTINATARIO = :UTENTE);
  EXECUTE PROCEDURE CARATT_CONTROLLA('GESTY-BAN-010', 'avviso di scadenza una volta sola', :QUANTI = 1, 'avvisi: ' || :QUANTI);

  -- GESTY-BAN-007 l'eliminazione del bando porta con se' i pareri
  EXECUTE PROCEDURE CARATT_ESEGUI('GESTY-BAN-007', 'eliminazione di un bando con pareri annullati', 'riuscito', NULL, 'DELETE FROM BANDI WHERE ID_BANDO = ' || :SCARTATO);

  DUMMY = RDB$SET_CONTEXT('USER_SESSION', 'CURRENT_ID_RISORSA', NULL);
  DUMMY = RDB$SET_CONTEXT('USER_SESSION', 'CURRENT_USER_ID', NULL);
  DELETE FROM USR_TMP_AUTHORIZATIONS;
END^

