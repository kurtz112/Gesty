-- Caratterizzazione di Rilevamento ore (specifica GESTY-RIL-*) sul banco di prova.
-- Ogni caso e' un blocco che prova una scrittura su ORE_RILEVATE e annota in CARATT_ESITI se e' riuscita
-- o con quale messaggio si e' fermata. Non verifica niente da solo: l'esito atteso dalla specifica sta
-- accanto a quello osservato, e il confronto si legge con 02-esiti.sql.
-- Dati: si riusano risorse, progetti e incarichi della copia del database di banco, in date future
-- senza altri rilevamenti. Lo script gira come SYSDBA, quindi le autorizzazioni (AUTH.*) e
-- CURRENT_ID_RISORSA() non rappresentano un utente reale: i casi che dipendono da loro lo dicono.
