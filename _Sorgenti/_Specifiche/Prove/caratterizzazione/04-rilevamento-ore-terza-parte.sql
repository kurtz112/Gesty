-- Terza parte della caratterizzazione di Rilevamento ore (specifica GESTY-RIL-*).
-- Riparte dalla madre (ricrea CARATT_ESITI). A differenza di 01 e 03 simula il contesto di un utente reale:
--   * CURRENT_ID_RISORSA() si imposta con RDB$SET_CONTEXT('USER_SESSION', 'CURRENT_ID_RISORSA', <risorsa>);
--   * le autorizzazioni (AUTH.*) leggono USR_TMP_AUTHORIZATIONS, che qui si svuota e si riempie con le sole
--     autorizzazioni del caso (CARATT_IMPOSTA); CARATT_RIPRISTINA rimette quelle di partenza.
-- Il contesto e' simulato: prova le regole dei trigger, non il modo in cui l'applicazione costruisce il contesto
-- (USR_CONTEXT_SET, USR_FILL_TABELLE_TMP). Date: gennaio 2027, senza altri rilevamenti per le risorse usate.
SET TERM ^ ;

CREATE TABLE CARATT_ESITI (
    ID        INTEGER GENERATED BY DEFAULT AS IDENTITY,
    REQUISITO VARCHAR(20) NOT NULL,
    CASO      VARCHAR(200) NOT NULL,
    ATTESO    VARCHAR(10) NOT NULL,
    ESITO     VARCHAR(10),
    MESSAGGIO VARCHAR(1000)
)^

CREATE TABLE CARATT_AUTH_SALVATE (
    AUTORIZZAZIONE VARCHAR(100) NOT NULL
)^

COMMIT^

CREATE PROCEDURE CARATT_REGISTRA (
    REQUISITO VARCHAR(20),
    CASO      VARCHAR(200),
    ATTESO    VARCHAR(10),
    MSG       VARCHAR(1000),
    ESITO     VARCHAR(10) = NULL)
AS
BEGIN
  INSERT INTO CARATT_ESITI (REQUISITO, CASO, ATTESO, ESITO, MESSAGGIO)
  VALUES (:REQUISITO, :CASO, :ATTESO, COALESCE(:ESITO, IIF(:MSG IS NULL, 'riuscito', 'errore')), :MSG);
END^

CREATE PROCEDURE CARATT_IMPOSTA (
    ID_RIS    BIGINT,
    VALIDA    BOOLEAN,
    SBLOCCA   BOOLEAN,
    RETTIFICA BOOLEAN,
    FATTURA   BOOLEAN,
    RECUPERO  BOOLEAN)
AS
DECLARE VARIABLE DUMMY VARCHAR(255);
BEGIN
  DELETE FROM USR_TMP_AUTHORIZATIONS;
  IF (:VALIDA) THEN
    INSERT INTO USR_TMP_AUTHORIZATIONS ("AUTHORIZATION") VALUES ('Risorse.ValidazioneOreRilevate');
  IF (:SBLOCCA) THEN
    INSERT INTO USR_TMP_AUTHORIZATIONS ("AUTHORIZATION") VALUES ('Risorse.SbloccoOreValidate');
  IF (:RETTIFICA) THEN
    INSERT INTO USR_TMP_AUTHORIZATIONS ("AUTHORIZATION") VALUES ('Risorse.RettificaOreValidate');
  IF (:FATTURA) THEN
    INSERT INTO USR_TMP_AUTHORIZATIONS ("AUTHORIZATION") VALUES ('Risorse.OreRilevateFatturate');
  IF (:RECUPERO) THEN
    INSERT INTO USR_TMP_AUTHORIZATIONS ("AUTHORIZATION") VALUES ('Risorse.OreRecuperoAttivitaDiverse');
  DUMMY = RDB$SET_CONTEXT('USER_SESSION', 'CURRENT_ID_RISORSA', :ID_RIS);
END^

CREATE PROCEDURE CARATT_RIPRISTINA
AS
DECLARE VARIABLE DUMMY VARCHAR(255);
BEGIN
  DELETE FROM USR_TMP_AUTHORIZATIONS;
  INSERT INTO USR_TMP_AUTHORIZATIONS ("AUTHORIZATION")
  SELECT CARATT_AUTH_SALVATE.AUTORIZZAZIONE FROM CARATT_AUTH_SALVATE;
  DUMMY = RDB$SET_CONTEXT('USER_SESSION', 'CURRENT_ID_RISORSA', NULL);
  DUMMY = RDB$SET_CONTEXT('USER_TRANSACTION', 'IMPORT_FILE_GRS', NULL);
  DUMMY = RDB$SET_CONTEXT('USER_TRANSACTION', 'ELABORAZIONE_PRESENZE', NULL);
  DUMMY = RDB$SET_CONTEXT('USER_TRANSACTION', 'BLOCCA_CONTROLLO_FIRMA_ORARIO', NULL);
END^

