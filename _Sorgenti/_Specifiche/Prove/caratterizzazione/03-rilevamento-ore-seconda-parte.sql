-- Seconda parte della caratterizzazione di Rilevamento ore (specifica GESTY-RIL-*).
-- Stesso metodo e stesse avvertenze di 01-rilevamento-ore.sql (gira come SYSDBA: le autorizzazioni non sono
-- quelle di un utente reale). Parte dalla madre, quindi ricrea CARATT_ESITI.
-- Dati: rilevamenti 620212 e 620213 (collegati all'orario, risorsa 80664, 09/09/2026), 340705 (collegato a una riga
-- di ORE_SOSTEGNO, risorsa 1310, 2023), incarico 502803 su un progetto con piani personalizzati (risorsa 469201).
SET TERM ^ ;

CREATE TABLE CARATT_ESITI (
    ID        INTEGER GENERATED BY DEFAULT AS IDENTITY,
    REQUISITO VARCHAR(20) NOT NULL,
    CASO      VARCHAR(120) NOT NULL,
    ATTESO    VARCHAR(10) NOT NULL,
    ESITO     VARCHAR(10),
    MESSAGGIO VARCHAR(1000)
)^

COMMIT^

-- GESTY-RIL-003: rilevamento senza incarico
EXECUTE BLOCK AS
DECLARE VARIABLE MSG VARCHAR(1000);
BEGIN
  MSG = NULL;
  BEGIN
    INSERT INTO ORE_RILEVATE (ID_RILEVATORE, ID_RISORSA, DATA, ORA_INIZIO, ORA_FINE, ID_PROGETTO, TIPO_INCARICO, ID_INCARICO)
    VALUES (1158, 1158, CAST('2027-04-28' AS DATE), '09:00:00', '10:00:00', 478163, 'Orientamento', NULL);
  WHEN ANY DO
    MSG = SUBSTRING(RDB$ERROR(MESSAGE) FROM 1 FOR 1000);
  END
  INSERT INTO CARATT_ESITI (REQUISITO, CASO, ATTESO, ESITO, MESSAGGIO)
  VALUES ('GESTY-RIL-003', 'rilevamento senza incarico', 'riuscito', IIF(:MSG IS NULL, 'riuscito', 'errore'), :MSG);
END^

-- GESTY-RIL-013: piano personalizzato mancante su un progetto che li richiede
EXECUTE BLOCK AS
DECLARE VARIABLE MSG VARCHAR(1000);
BEGIN
  MSG = NULL;
  BEGIN
    INSERT INTO ORE_RILEVATE (ID_RILEVATORE, ID_RISORSA, DATA, ORA_INIZIO, ORA_FINE, ID_PROGETTO, TIPO_INCARICO, ID_INCARICO, ID_PIANO_PERSONALIZZATO)
    VALUES (469201, 469201, CAST('2026-12-16' AS DATE), '09:00:00', '10:00:00', 501267, 'PIP', 502803, NULL);
  WHEN ANY DO
    MSG = SUBSTRING(RDB$ERROR(MESSAGE) FROM 1 FOR 1000);
  END
  INSERT INTO CARATT_ESITI (REQUISITO, CASO, ATTESO, ESITO, MESSAGGIO)
  VALUES ('GESTY-RIL-013', 'piano personalizzato mancante', 'errore', IIF(:MSG IS NULL, 'riuscito', 'errore'), :MSG);
END^

-- GESTY-RIL-012: spostamento di un rilevamento citato dall'orario
EXECUTE BLOCK AS
DECLARE VARIABLE MSG VARCHAR(1000);
BEGIN
  MSG = NULL;
  BEGIN
    UPDATE ORE_RILEVATE
    SET
        ORE_RILEVATE.ORA_INIZIO = '18:30:00'
    WHERE
        ORE_RILEVATE.ID_RILEVAMENTO_ORE = 620213;
  WHEN ANY DO
    MSG = SUBSTRING(RDB$ERROR(MESSAGE) FROM 1 FOR 1000);
  END
  INSERT INTO CARATT_ESITI (REQUISITO, CASO, ATTESO, ESITO, MESSAGGIO)
  VALUES ('GESTY-RIL-012', 'spostamento dell ora di inizio di un rilevamento legato all orario', 'errore', IIF(:MSG IS NULL, 'riuscito', 'errore'), :MSG);
END^

-- DIV-RIL-8: lo stesso rilevamento legato all'orario si puo' cancellare, e la riga dell'orario lo perde
EXECUTE BLOCK AS
DECLARE VARIABLE MSG VARCHAR(1000);
DECLARE VARIABLE RIGHE_ORARIO_PRIMA INTEGER;
DECLARE VARIABLE RIGHE_ORARIO_DOPO INTEGER;
BEGIN
  MSG = NULL;
  RIGHE_ORARIO_PRIMA = (SELECT COUNT(*) FROM ORARIO WHERE ORARIO.ID_RILEVAMENTO_ORE = 620213);
  BEGIN
    DELETE FROM ORE_RILEVATE
    WHERE
        ORE_RILEVATE.ID_RILEVAMENTO_ORE = 620213;
  WHEN ANY DO
    MSG = SUBSTRING(RDB$ERROR(MESSAGE) FROM 1 FOR 1000);
  END
  RIGHE_ORARIO_DOPO = (SELECT COUNT(*) FROM ORARIO WHERE ORARIO.ID_RILEVAMENTO_ORE = 620213);
  INSERT INTO CARATT_ESITI (REQUISITO, CASO, ATTESO, ESITO, MESSAGGIO)
  VALUES ('DIV-RIL-8', 'cancellazione di un rilevamento legato all orario (la divergenza dice: riesce)', 'riuscito', IIF(:MSG IS NULL, 'riuscito', 'errore'),
          COALESCE(:MSG, 'righe dell orario che lo citavano: prima ' || :RIGHE_ORARIO_PRIMA || ', dopo ' || :RIGHE_ORARIO_DOPO));
END^

-- GESTY-RIL-018: cancellazione di un rilevamento citato da ORE_SOSTEGNO; la riga di sostegno resta senza rilevamento
EXECUTE BLOCK AS
DECLARE VARIABLE MSG VARCHAR(1000);
DECLARE VARIABLE SOSTEGNO_PRIMA INTEGER;
DECLARE VARIABLE SOSTEGNO_DOPO INTEGER;
DECLARE VARIABLE CITANO_ANCORA INTEGER;
BEGIN
  MSG = NULL;
  SOSTEGNO_PRIMA = (SELECT COUNT(*) FROM ORE_SOSTEGNO);
  BEGIN
    DELETE FROM ORE_RILEVATE
    WHERE
        ORE_RILEVATE.ID_RILEVAMENTO_ORE = 340705;
  WHEN ANY DO
    MSG = SUBSTRING(RDB$ERROR(MESSAGE) FROM 1 FOR 1000);
  END
  SOSTEGNO_DOPO = (SELECT COUNT(*) FROM ORE_SOSTEGNO);
  CITANO_ANCORA = (SELECT COUNT(*) FROM ORE_SOSTEGNO WHERE ORE_SOSTEGNO.ID_RILEVAMENTO_ORE = 340705);
  INSERT INTO CARATT_ESITI (REQUISITO, CASO, ATTESO, ESITO, MESSAGGIO)
  VALUES ('GESTY-RIL-018', 'cancellazione di un rilevamento citato da ORE_SOSTEGNO', 'riuscito',
          IIF(:MSG IS NULL AND :SOSTEGNO_PRIMA = :SOSTEGNO_DOPO AND :CITANO_ANCORA = 0, 'riuscito', 'errore'),
          COALESCE(:MSG, 'righe di sostegno: prima ' || :SOSTEGNO_PRIMA || ', dopo ' || :SOSTEGNO_DOPO || '; ancora collegate: ' || :CITANO_ANCORA));
END^

