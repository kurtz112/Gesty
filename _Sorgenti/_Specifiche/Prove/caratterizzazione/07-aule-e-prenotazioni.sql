CREATE TABLE CARATT_ESITI (
    ID        INTEGER GENERATED BY DEFAULT AS IDENTITY,
    REQUISITO VARCHAR(20) NOT NULL,
    CASO      VARCHAR(200) NOT NULL,
    ATTESO    VARCHAR(10) NOT NULL,
    ESITO     VARCHAR(10),
    MESSAGGIO VARCHAR(1000)
)^

CREATE TABLE CARATT_AUTH_SALVATE (
    AUTORIZZAZIONE VARCHAR(100) NOT NULL
)^

COMMIT^

CREATE PROCEDURE CARATT_REGISTRA (
    REQUISITO VARCHAR(20),
    CASO      VARCHAR(200),
    ATTESO    VARCHAR(10),
    MSG       VARCHAR(1000),
    ESITO     VARCHAR(10) = NULL)
AS
BEGIN
  INSERT INTO CARATT_ESITI (REQUISITO, CASO, ATTESO, ESITO, MESSAGGIO)
  VALUES (:REQUISITO, :CASO, :ATTESO, COALESCE(:ESITO, IIF(:MSG IS NULL, 'riuscito', 'errore')), :MSG);
END^

-- Utente simulato: risorsa del richiedente e autorizzazioni di Aule
CREATE PROCEDURE CARATT_UTENTE (
    RIS         BIGINT,
    INSERIMENTO BOOLEAN,
    MODIFICA    BOOLEAN,
    DEROGA      BOOLEAN = FALSE,
    GESTIONE    BOOLEAN = FALSE)
AS
DECLARE VARIABLE DUMMY VARCHAR(255);
BEGIN
  DELETE FROM USR_TMP_AUTHORIZATIONS;
  IF (:GESTIONE) THEN
    INSERT INTO USR_TMP_AUTHORIZATIONS ("AUTHORIZATION") VALUES ('Aule.Gestione');
  IF (:INSERIMENTO) THEN
    INSERT INTO USR_TMP_AUTHORIZATIONS ("AUTHORIZATION") VALUES ('Aule.Prenotazioni.Inserimento');
  IF (:MODIFICA) THEN
    INSERT INTO USR_TMP_AUTHORIZATIONS ("AUTHORIZATION") VALUES ('Aule.Prenotazioni.Modifica');
  IF (:DEROGA) THEN
    INSERT INTO USR_TMP_AUTHORIZATIONS ("AUTHORIZATION") VALUES ('Aule.Prenotazioni.DerogaLimiteTemporale');
  DUMMY = RDB$SET_CONTEXT('USER_SESSION', 'CURRENT_ID_RISORSA', :RIS);
  DUMMY = RDB$SET_CONTEXT('USER_SESSION', 'CURRENT_USER_ID', (SELECT FIRST 1 USR_UTENTI.USER_ID FROM USR_UTENTI ORDER BY USR_UTENTI.USER_ID));
END^

CREATE PROCEDURE CARATT_RIPRISTINA
AS
DECLARE VARIABLE DUMMY VARCHAR(255);
BEGIN
  DELETE FROM USR_TMP_AUTHORIZATIONS;
  INSERT INTO USR_TMP_AUTHORIZATIONS ("AUTHORIZATION")
  SELECT CARATT_AUTH_SALVATE.AUTORIZZAZIONE FROM CARATT_AUTH_SALVATE;
