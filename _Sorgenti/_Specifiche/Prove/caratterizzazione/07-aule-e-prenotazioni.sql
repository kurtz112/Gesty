-- Identificativo della prenotazione di un'aula in un giorno a una certa ora di inizio (di preferenza quella attiva)
CREATE FUNCTION CARATT_ID (
    CODICE_AULA VARCHAR(20),
    GIORNO      DATE,
    INIZIO      TIME)
RETURNS BIGINT
AS
BEGIN
  RETURN (SELECT FIRST 1
              AULE_PRENOTAZIONI.ID_PRENOTAZIONE_AULA
          FROM
              AULE_PRENOTAZIONI
          WHERE
              AULE_PRENOTAZIONI.AULA = :CODICE_AULA AND
              AULE_PRENOTAZIONI.DATA_PRENOTAZIONE = :GIORNO AND
              AULE_PRENOTAZIONI.ORA_INIZIO = :INIZIO
          ORDER BY
              AULE_PRENOTAZIONI.ANNULLATA,
              AULE_PRENOTAZIONI.ID_PRENOTAZIONE_AULA DESC);
END^

-- Quante prenotazioni ci sono in un'aula in un giorno (INIZIO nullo = a qualunque ora)
CREATE FUNCTION CARATT_QUANTE (
    CODICE_AULA VARCHAR(20),
    GIORNO      DATE,
    INIZIO      TIME,
    SOLO_ATTIVE BOOLEAN)
RETURNS INTEGER
AS
BEGIN
  RETURN (SELECT
              COUNT(*)
          FROM
              AULE_PRENOTAZIONI
          WHERE
              AULE_PRENOTAZIONI.AULA = :CODICE_AULA AND
              AULE_PRENOTAZIONI.DATA_PRENOTAZIONE = :GIORNO AND
              (:INIZIO IS NULL OR AULE_PRENOTAZIONI.ORA_INIZIO = :INIZIO) AND
              (:SOLO_ATTIVE = FALSE OR AULE_PRENOTAZIONI.ANNULLATA = FALSE));
END^

