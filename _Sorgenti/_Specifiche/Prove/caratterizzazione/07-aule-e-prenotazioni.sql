  RESPONSABILE = (SELECT FIRST 1 USR_UTENTI.ID_ANAGRAFICA FROM USR_UTENTI INNER JOIN PERSONALE ON PERSONALE.ID_PERSONALE = USR_UTENTI.ID_ANAGRAFICA
                  ORDER BY USR_UTENTI.USER_ID);
