-- Caratterizzazione di Presenze allievi e registro (specifica GESTY-PRE-*), seconda puntata: i requisiti rimasti.
-- Riparte dalla madre (ricrea CARATT_ESITI). Copre PRE-006, 010, 011, 013, 015 (rilevamento del docente), 017 e
-- DIV-PRE-3, 4, 7, 8, 9.
-- Dati: progetto 470701 corso 473403 (allievi 443455, 473407, 86440) e progetto 85470 senza corso (allievo 85762,
-- piano 86638, risorsa 84154, incarico 135963 di giugno 2024). Le lezioni di prova sono nuove e si registrano in CARATT_MIE.
-- Le autorizzazioni si simulano con USR_TMP_AUTHORIZATIONS (CARATT_SOLO / CARATT_RIPRISTINA), come nella terza parte di Rilevamento ore.
SET TERM ^ ;

CREATE TABLE CARATT_ESITI (
    ID        INTEGER GENERATED BY DEFAULT AS IDENTITY,
    REQUISITO VARCHAR(20) NOT NULL,
    CASO      VARCHAR(200) NOT NULL,
    ATTESO    VARCHAR(10) NOT NULL,
    ESITO     VARCHAR(10),
    MESSAGGIO VARCHAR(1000)
)^

CREATE TABLE CARATT_AUTH_SALVATE (
    AUTORIZZAZIONE VARCHAR(100) NOT NULL
)^

CREATE TABLE CARATT_MIE (
    ID_ORARIO BIGINT NOT NULL
)^

CREATE TABLE CARATT_AGGIORNATE (
    ID_PRESENZA BIGINT NOT NULL
)^

COMMIT^

CREATE PROCEDURE CARATT_REGISTRA (
    REQUISITO VARCHAR(20),
    CASO      VARCHAR(200),
    ATTESO    VARCHAR(10),
    MSG       VARCHAR(1000),
    ESITO     VARCHAR(10) = NULL)
AS
BEGIN
  INSERT INTO CARATT_ESITI (REQUISITO, CASO, ATTESO, ESITO, MESSAGGIO)
  VALUES (:REQUISITO, :CASO, :ATTESO, COALESCE(:ESITO, IIF(:MSG IS NULL, 'riuscito', 'errore')), :MSG);
END^

CREATE VIEW CARATT_LEZIONI (ID_ORARIO, ID_PROGETTO, DATA_LEZIONE, ORA_INIZIO) AS
SELECT
    ORARIO.ID_ORARIO,
    ORARIO.ID_PROGETTO,
    ORARIO.DATA_LEZIONE,
    ORARIO.ORA_INIZIO
FROM
    ORARIO
        INNER JOIN CARATT_MIE ON CARATT_MIE.ID_ORARIO = ORARIO.ID_ORARIO^

CREATE PROCEDURE CARATT_NUOVA_LEZIONE (
    ID_PROG  BIGINT,
    ID_COR   BIGINT,
    DATA_LEZ DATE,
    ORA_N    SMALLINT,
    ORA_INI  TIME,
    SVOLTA   BOOLEAN = TRUE,
    DOCENTE  BIGINT = NULL,
    INCARICO BIGINT = NULL,
    MAT      VARCHAR(150) = NULL)
AS
DECLARE VARIABLE ID_NUOVO BIGINT;
BEGIN
  INSERT INTO ORARIO (DATA_LEZIONE, ORA, ORA_INIZIO, DURATA, ID_PROGETTO, ID_CORSO, LEZIONE_SVOLTA, ID_DOCENTE, ID_INCARICO, MATERIA)
  VALUES (:DATA_LEZ, :ORA_N, :ORA_INI, 60, :ID_PROG, :ID_COR, :SVOLTA, :DOCENTE, :INCARICO, :MAT)
  RETURNING ORARIO.ID_ORARIO INTO :ID_NUOVO;
  INSERT INTO CARATT_MIE (ID_ORARIO) VALUES (:ID_NUOVO);
END^

-- Presenza collettiva su una lezione di prova indicata da data e ora di inizio
CREATE PROCEDURE CARATT_PRESENZA (
    ID_STUD    BIGINT,
    DATA_LEZ   DATE,
    ORA_INI    TIME,
    STATO      VARCHAR(1))
RETURNS (ID_NUOVA BIGINT)
AS
BEGIN
  INSERT INTO STUDENTI_PRESENZE_COLLETTIVA (ID_ORARIO, ID_STUDENTE, STATO_PRESENZA)
  VALUES ((SELECT CARATT_LEZIONI.ID_ORARIO FROM CARATT_LEZIONI
           WHERE CARATT_LEZIONI.DATA_LEZIONE = :DATA_LEZ AND CARATT_LEZIONI.ORA_INIZIO = :ORA_INI),
          :ID_STUD, :STATO)
  RETURNING STUDENTI_PRESENZE_COLLETTIVA.ID_PRESENZA_COLLETTIVA INTO :ID_NUOVA;
  SUSPEND;
END^

