-- Tiene solo le autorizzazioni indicate
CREATE PROCEDURE CARATT_SOLO (
    A1 VARCHAR(100) = NULL,
    A2 VARCHAR(100) = NULL)
AS
BEGIN
  DELETE FROM USR_TMP_AUTHORIZATIONS;
  IF (:A1 IS NOT NULL) THEN
    INSERT INTO USR_TMP_AUTHORIZATIONS ("AUTHORIZATION") VALUES (:A1);
  IF (:A2 IS NOT NULL) THEN
    INSERT INTO USR_TMP_AUTHORIZATIONS ("AUTHORIZATION") VALUES (:A2);
END^

CREATE PROCEDURE CARATT_RIPRISTINA
AS
BEGIN
  DELETE FROM USR_TMP_AUTHORIZATIONS;
  INSERT INTO USR_TMP_AUTHORIZATIONS ("AUTHORIZATION")
  SELECT CARATT_AUTH_SALVATE.AUTORIZZAZIONE FROM CARATT_AUTH_SALVATE;
END^

